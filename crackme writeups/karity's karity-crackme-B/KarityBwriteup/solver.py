# Генерация логов (настоящий sub_140001000)
LOG_DATA = [0] * 256
for i in range(255):
    LOG_DATA[EXP_DATA[i]] = i

ctx = z3.Context()
# Используем жесткий bvector-солвер, он создан для таких задач
s = z3.SolverFor("QF_BV", ctx=ctx)

v41_bytes = list((0x26B703D14FC4C9A).to_bytes(8, 'little'))
v42_bytes = list((0x5FE21933C7A15581).to_bytes(8, 'little'))
const_matrix = v41_bytes + v42_bytes

# ПРЕКОМПИЛЯЦИЯ ТАБЛИЦ ДЛЯ КАЖДОЙ КОНСТАНТЫ ИЗ МАТРИЦЫ
lut_arrays = []
for k in range(16):
    c = const_matrix[k]
    lut_data = [0] * 256
    for a in range(256):
        if a == 0 or c == 0:
            lut_data[a] = 0
        else:
            sum_log = (LOG_DATA[a] + LOG_DATA[c]) % 255
            lut_data[a] = EXP_DATA[sum_log]
            
    # Переносим готовую таблицу в Z3 статичным массивом
    z3_arr = z3.Array(f'lut_{k}', z3.BitVecSort(8, ctx), z3.BitVecSort(8, ctx))
    for idx, val in enumerate(lut_data):
        s.add(z3.Select(z3_arr, z3.BitVecVal(idx, 8, ctx)) == z3.BitVecVal(val, 8, ctx))
    lut_arrays.append(z3_arr)

# Переменные флага
input_bytes = []
known_prefix = b"KARITY{sec"

for i in range(36):
    if i < len(known_prefix):
        input_bytes.append(z3.BitVecVal(known_prefix[i], 8, ctx))
    elif i == 35:
        input_bytes.append(z3.BitVecVal(ord('}'), 8, ctx))
    else:
        v = z3.BitVec(f"char_{i}", 8, ctx)
        s.add(z3.And(v >= 0x20, v <= 0x7E))
        s.add(z3.Or(v < 65, v > 90)) # Без uppercase
        input_bytes.append(v)

state = [z3.BitVecVal(0, 8, ctx) for _ in range(16)]

# Симуляция хэширования без внутренней арифметики Z3
print("[*] Building optimized state graph...")
for v1, v6 in enumerate(input_bytes):
    v7 = (3 * v1) & 0xFF
    
    for step, v8 in enumerate([3, 11]):
        k = step * 8
        
        idx0 = (v8 - 3 + v7 + 4 * (v8 - 3)) & 0xF
        state[idx0] = z3.Select(lut_arrays[k + 0], state[idx0]) ^ v6
        
        idx1 = (v8 - 3 + v7 + 4 * (v8 - 3) + 5) & 0xF
        state[idx1] = z3.Select(lut_arrays[k + 1], state[idx1]) ^ v6
        
        idx2 = (v7 + 4 * (v8 - 1) + v8 - 1) & 0xF
        state[idx2] = z3.Select(lut_arrays[k + 2], state[idx2]) ^ v6
        
        idx3 = (v8 + v7 + 4 * v8) & 0xF
        state[idx3] = z3.Select(lut_arrays[k + 3], state[idx3]) ^ v6
        
        idx4 = (v7 + 4 * (v8 + 1) + v8 + 1) & 0xF
        state[idx4] = z3.Select(lut_arrays[k + 4], state[idx4]) ^ v6
        
        idx5 = (v8 + v7 + 4 * v8 - 6) & 0xF
        state[idx5] = z3.Select(lut_arrays[k + 5], state[idx5]) ^ v6
        
        idx6 = (v8 + v7 + 4 * v8 - 1) & 0xF
        state[idx6] = z3.Select(lut_arrays[k + 6], state[idx6]) ^ v6
        
        idx7 = (v8 + v7 + 4 * (v8 + 1)) & 0xF
        state[idx7] = z3.Select(lut_arrays[k + 7], state[idx7]) ^ v6

# сравниваем результаты обязательно
target_low = (0x7CD81D08347C7C08).to_bytes(8, 'little')
target_high = (0x7C3140977C64EFA8).to_bytes(8, 'little')
target_hash = target_low + target_high

for i in range(16):
    s.add(state[i] == z3.BitVecVal(target_hash[i], 8, ctx))

print("[*] Running QF_BV Solver...")
if s.check() == z3.sat:
    m = s.model()
    flag = ""
    for i in range(36):
        # извлекаем байты
        val = m.eval(input_bytes[i], model_completion=True)
        flag += chr(val.as_long())
    print(f"\n[+] Flag found: {flag}")
else:
    print("\n[-] Unsat. Проверь корректность условий.")